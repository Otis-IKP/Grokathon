import fs from "node:fs";
import path from "node:path";
import { botToolDefinitions, botTools } from "@/server/bot/tools";

/**
 * Writes docs/bot-tools.json (xAI function definitions for Tobi's Grok agent)
 * and the Bot API section of docs/api.md. Both come from src/server/bot/tools.ts,
 * the same schemas the route handlers validate with.
 */
const docs = path.join(process.cwd(), "docs");
fs.mkdirSync(docs, { recursive: true });

const definitions = botToolDefinitions();
fs.writeFileSync(path.join(docs, "bot-tools.json"), `${JSON.stringify(definitions, null, 2)}\n`);

const lines: string[] = [
  "<!-- BEGIN:bot-api (generated by `pnpm gen:bot-tools`; edit src/server/bot/tools.ts instead) -->",
  "",
  "## Bot API",
  "",
  "Every request carries `Authorization: Bearer {BOT_API_SECRET}`. Bodies are JSON. Each tool in",
  "`docs/bot-tools.json` maps to one endpoint; for `GET` the arguments are query parameters, and",
  "`{intro_id}` in a path is taken from the arguments.",
  "",
  "Errors are `{ \"error\": { \"code\", \"message\" } }` with an HTTP status. `401 unauthenticated` means the",
  "bearer secret is missing or wrong; `400 invalid_request` lists the fields that failed validation.",
  "",
];
for (const tool of botTools) {
  const def = definitions.find((d) => d.name === tool.name)!;
  const props = (def.parameters.properties ?? {}) as Record<string, { type?: string; description?: string }>;
  const required = new Set((def.parameters.required as string[] | undefined) ?? []);
  lines.push(`### \`${tool.name}\` — \`${tool.method} ${tool.path}\``, "", tool.description, "");
  lines.push("| Argument | Required | Description |", "|---|---|---|");
  for (const [key, prop] of Object.entries(props)) {
    lines.push(`| \`${key}\` | ${required.has(key) ? "yes" : "no"} | ${(prop.description ?? "").replace(/\|/g, "\\|")} |`);
  }
  lines.push("", `Returns: \`${tool.returns}\``, "");
  if (tool.errors.length > 0) lines.push(`Error codes: ${tool.errors.map((e) => `\`${e}\``).join(", ")}`, "");
}
lines.push("<!-- END:bot-api -->");

const apiFile = path.join(docs, "api.md");
const block = lines.join("\n");
let current = fs.existsSync(apiFile) ? fs.readFileSync(apiFile, "utf8") : "# NEPO API reference\n";
const pattern = /<!-- BEGIN:bot-api[\s\S]*?<!-- END:bot-api -->/;
current = pattern.test(current) ? current.replace(pattern, block) : `${current.trimEnd()}\n\n${block}\n`;
fs.writeFileSync(apiFile, current);

console.log(`Wrote docs/bot-tools.json (${definitions.length} tools) and the Bot API section of docs/api.md.`);
